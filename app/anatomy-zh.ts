function normalize(name: string): string {
  return name.trim().toLowerCase().replace(/\s+/g, ' ');
}

export function anatomyChinese(name: string): string | undefined {
  const key = normalize(name);
  if (ANATOMY_ZH[key]) return ANATOMY_ZH[key];

  // 只处理明确的左/右修饰，不对未知术语做猜测翻译。
  const sideMatch =
    key.match(/^(left|right)\s+(.+)$/) ??
    key.match(/^(.+),\s*(left|right)$/);

  if (sideMatch) {
    const prefixForm = sideMatch[1] === 'left' || sideMatch[1] === 'right';
    const side = prefixForm ? sideMatch[1] : sideMatch[2];
    const base = prefixForm ? sideMatch[2] : sideMatch[1];
    const translated = anatomyChinese(base);
    if (translated) return (side === 'left' ? '左侧' : '右侧') + translated;
  }

  const rib = key.match(/^rib\s+(\d+)$/);
  if (rib) return '第' + rib[1] + '肋骨';

  // 英文序数词 → 中文数字
  const ORDINAL: Record<string, string> = {
    'first': '1', 'second': '2', 'third': '3', 'fourth': '4',
    'fifth': '5', 'sixth': '6', 'seventh': '7', 'eighth': '8',
    'ninth': '9', 'tenth': '10', 'eleventh': '11', 'twelfth': '12'
  };

  // 椎骨：Seventh cervical vertebra → 第7颈椎
  const vertebraOrdinal = key.match(/^(first|second|third|fourth|fifth|sixth|seventh|eighth|ninth|tenth|eleventh|twelfth)\s+(cervical|thoracic|lumbar)\s+vertebra$/);
  if (vertebraOrdinal) {
    const names: Record<string, string> = {
      cervical: '颈椎', thoracic: '胸椎', lumbar: '腰椎'
    };
    return '第' + ORDINAL[vertebraOrdinal[1]] + names[vertebraOrdinal[2]];
  }

  // 肋骨：Left seventh rib → 左侧第7肋骨
  const ribOrdinal = key.match(/^(left|right)\s+(first|second|third|fourth|fifth|sixth|seventh|eighth|ninth|tenth|eleventh|twelfth)\s+rib$/);
  if (ribOrdinal) {
    const side = ribOrdinal[1] === 'left' ? '左侧' : '右侧';
    return side + '第' + ORDINAL[ribOrdinal[2]] + '肋骨';
  }

  // 掌骨/跖骨：Left first metacarpal bone → 左侧第1掌骨
  const metaOrdinal = key.match(/^(left|right)\s+(first|second|third|fourth|fifth)\s+(metacarpal|metatarsal)\s+bone$/);
  if (metaOrdinal) {
    const side = metaOrdinal[1] === 'left' ? '左侧' : '右侧';
    const bone = metaOrdinal[3] === 'metacarpal' ? '掌骨' : '跖骨';
    return side + '第' + ORDINAL[metaOrdinal[2]] + bone;
  }

  const vertebra = key.match(/^(cervical|thoracic|lumbar) vertebra\s+(\d+)$/);
  if (vertebra) {
    const names: Record<string, string> = {
      cervical: '颈椎', thoracic: '胸椎', lumbar: '腰椎'
    };
    return '第' + vertebra[2] + names[vertebra[1]];
  }

  // 序数词+骨骼名：First rib → 第1肋，Fifth metacarpal bone → 第5掌骨
  const ordinalBoneMatch = key.match(/^(first|second|third|fourth|fifth|sixth|seventh|eighth|ninth|tenth|eleventh|twelfth)\s+(.+)$/);
  if (ordinalBoneMatch) {
    const ordMap: Record<string, string> = {
      first: '1', second: '2', third: '3', fourth: '4', fifth: '5',
      sixth: '6', seventh: '7', eighth: '8', ninth: '9', tenth: '10',
      eleventh: '11', twelfth: '12'
    };
    const base = anatomyChinese(ordinalBoneMatch[2]);
    if (base) return '第' + ordMap[ordinalBoneMatch[1]] + base;
  }

  // 指骨/趾骨：Distal phalanx of left index finger → 左手示指远节指骨
  const phalanxMatch = key.match(/^(distal|middle|proximal)\s+phalanx\s+of\s+(left|right)\s+(.+)$/);
  if (phalanxMatch) {
    const phalanxZh: Record<string, string> = {
      distal: '远节', middle: '中节', proximal: '近节'
    };
    const fingerZh: Record<string, string> = {
      'thumb': '拇指', 'index finger': '示指', 'middle finger': '中指',
      'ring finger': '环指', 'little finger': '小指',
      'big toe': '拇趾', 'second toe': '第2趾', 'third toe': '第3趾',
      'fourth toe': '第4趾', 'little toe': '小趾'
    };
    const side = phalanxMatch[2] === 'left' ? '左' : '右';
    const limb = phalanxMatch[3].includes('toe') ? '足' : '手';
    const digit = fingerZh[phalanxMatch[3]] || phalanxMatch[3];
    return side + limb + digit + phalanxZh[phalanxMatch[1]] + '指骨';
  }

  // 椎间盘：Intervertebral disk of fifth cervical vertebra → 第5颈椎椎间盘
  const diskMatch = key.match(/^intervertebral disk of (.+)$/);
  if (diskMatch) {
    const base = anatomyChinese(diskMatch[1]);
    if (base) return base + '椎间盘';
  }

  // 足舟骨：Navicular bone of left foot → 左侧足舟骨
  const navicularMatch = key.match(/^navicular bone of (left|right) foot$/);
  if (navicularMatch) {
    const side = navicularMatch[1] === 'left' ? '左侧' : '右侧';
    return side + '足舟骨';
  }

  // 籽骨：Sesamoid bone of left foot → 左足籽骨
  const sesamoidMatch = key.match(/^sesamoid bone of (left|right) foot$/);
  if (sesamoidMatch) {
    const side = sesamoidMatch[1] === 'left' ? '左' : '右';
    return side + '足籽骨';
  }

  // 牙齿：Lower central secondary incisor tooth → 下颌恒中切牙
  const toothMatch = key.match(/^(lower|upper)\s+(.+)\s+tooth$/);
  if (toothMatch) {
    const jaw = toothMatch[1] === 'lower' ? '下颌' : '上颌';
    const toothType = toothMatch[2]
      .replace('central secondary incisor', '恒中切')
      .replace('lateral secondary incisor', '恒侧切')
      .replace('first secondary premolar', '恒第一前磨')
      .replace('second secondary premolar', '恒第二前磨')
      .replace('first secondary molar', '恒第一磨')
      .replace('second secondary molar', '恒第二磨')
      .replace('secondary canine', '恒尖');
    return jaw + toothType + '牙';
  }

  // 肌肉部分：abdominal part of pectoralis major → 胸大肌腹部
  const partMatch = key.match(/^(\w[\w\s]*?)\s+part\s+of\s+(left|right)\s+(.+)$/);
  if (partMatch) {
    const partZh: Record<string, string> = {
      abdominal: '腹部', clavicular: '锁骨部', sternocostal: '胸肋部',
      acromial: '肩峰部', spinal: '脊柱部', ascending: '下部（升部）',
      descending: '上部（降部）', transverse: '中部（横部）', straight: '直部', oblique: '斜部',
      superior: '上部', inferior: '下部', vertical: '垂直部',
      'superior oblique': '上斜部', 'inferior oblique': '下斜部',
      'vertical intermediate': '垂直中间部'
    };
    const side = partMatch[2] === 'left' ? '左侧' : '右侧';
    const base = anatomyChinese(partMatch[3]);
    const part = partZh[partMatch[1]] || partMatch[1];
    if (base) return side + base + part;
  }

  // 肌肉头：long head of left biceps brachii → 左侧肱二头肌长头
  const headMatch = key.match(/^(long|short|lateral|medial|humeral|ulnar|oblique|transverse|superficial|deep|anterolateral)\s+head\s+of\s+(left|right)\s+(.+)$/);
  if (headMatch) {
    const headZh: Record<string, string> = {
      long: '长头', short: '短头', lateral: '外侧头', medial: '内侧头',
      humeral: '肱头', ulnar: '尺头', oblique: '斜头', transverse: '横头',
      superficial: '浅头', deep: '深头', anterolateral: '前外侧头'
    };
    const side = headMatch[2] === 'left' ? '左侧' : '右侧';
    const base = anatomyChinese(headMatch[3]);
    const head = headZh[headMatch[1]] || headMatch[1] + '头';
    if (base) return side + base + head;
  }

  // 手足序数词肌肉：First lumbrical of right foot → 右足第一蚓状肌
  const footHandMatch = key.match(/^(first|second|third|fourth|fifth|sixth|seventh|eighth)\s+(.+?)\s+of\s+(left|right)\s+(foot|hand)$/);
  if (footHandMatch) {
    const ord: Record<string, string> = {
      first: '第一', second: '第二', third: '第三', fourth: '第四',
      fifth: '第五', sixth: '第六', seventh: '第七', eighth: '第八'
    };
    const side = footHandMatch[3] === 'left' ? '左' : '右';
    const limb = footHandMatch[4] === 'foot' ? '足' : '手';
    const base = anatomyChinese(footHandMatch[2]);
    if (base) return side + limb + ord[footHandMatch[1]] + base;
  }

  // 心室乳头肌：anterior papillary muscle of right ventricle → 右心室前乳头肌
  const papillaryMatch = key.match(/^(anterior|posterior|septal|lateral|anterolateral)\s+(papillary muscle)\s+of\s+(left|right)\s+ventricle$/);
  if (papillaryMatch) {
    const posZh: Record<string, string> = {
      anterior: '前', posterior: '后', septal: '隔侧', lateral: '外侧', anterolateral: '前外侧'
    };
    const side = papillaryMatch[3] === 'left' ? '左' : '右';
    return side + '心室' + posZh[papillaryMatch[1]] + '乳头肌';
  }

  // 提肋肌集合：set of left levatores costarum breves → 左侧短提肋肌
  const levatoresMatch = key.match(/^set\s+of\s+(left|right)\s+(levatores costarum (breves|longi))$/);
  if (levatoresMatch) {
    const side = levatoresMatch[1] === 'left' ? '左侧' : '右侧';
    const base = anatomyChinese(levatoresMatch[2]);
    if (base) return side + base;
  }

  // 肌肉集合：set of dorsal interossei → 骨间背侧肌
  const setMatch = key.match(/^set\s+of\s+(.+)$/);
  if (setMatch) {
    const base = anatomyChinese(setMatch[1]);
    if (base) return base;
  }

  return undefined;
}

export function anatomyLabel(name: string): string {
  const chinese = anatomyChinese(name);
  return chinese ? chinese + ' · ' + name : name + '（中文待校对）';
}

export function anatomySearch(name: string): string {
  return (name + ' ' + (anatomyChinese(name) ?? '')).toLowerCase();
}

